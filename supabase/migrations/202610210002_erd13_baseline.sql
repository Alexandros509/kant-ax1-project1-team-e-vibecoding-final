CREATE FUNCTION check_category_depth() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.parent_id=NEW.id OR (NEW.parent_id IS NOT NULL AND EXISTS(SELECT 1 FROM categories WHERE id=NEW.parent_id AND parent_id IS NOT NULL)) OR (NEW.parent_id IS NOT NULL AND EXISTS(SELECT 1 FROM categories WHERE parent_id=NEW.id)) THEN
  RAISE EXCEPTION 'Categories must form an acyclic two-level hierarchy';
 END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER categories_two_levels BEFORE INSERT OR UPDATE ON categories FOR EACH ROW EXECUTE FUNCTION check_category_depth();
